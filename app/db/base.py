from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

# A fixed naming convention gives every index and constraint a predictable name.
# Without it, Postgres generates names that Alembic can't reliably find later
# when a migration needs to drop or alter a constraint.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
